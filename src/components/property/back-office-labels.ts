export function backOfficeLabel(text: string, concept: boolean): string {
  if (!concept) return text;
  const label = text.trim();
  const numbered =
    /^(Scope item|Internal unit cost|Cost markup %|Selling unit price|Option for item|Internal line note|Payment milestone|Payment share|Payment due date) (\d+)$/.exec(
      label,
    );
  if (numbered) return labels[numbered[1]] + ' ' + numbered[2];
  const finding =
    /^Finding (\d+) (location|category|severity|description|recommendation)$/.exec(
      label,
    );
  if (finding)
    return (
      'Finding ' +
      finding[1] +
      ' ' +
      (
        {
          location: 'Location',
          category: 'Category',
          severity: 'Severity',
          description: 'Description',
          recommendation: 'Recommendation',
        } as const
      )[finding[2] as 'location']
    );
  return text.replace(label, labels[label] ?? label);
}
